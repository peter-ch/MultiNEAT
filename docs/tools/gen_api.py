#!/usr/bin/env python3
"""Generates docs/api.md from the signatures and docstrings of the compiled module.

usage: python docs/tools/gen_api.py
"""
import inspect
import os
import re

import MultiNEAT as NEAT
from MultiNEAT import physics2d

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'docs', 'api.md')

CLASSES = [
    ('Evolution', ['Parameters', 'Population', 'Species', 'RNG']),
    ('Genomes', ['Genome', 'GenomeInitStruct', 'NeuronGene', 'LinkGene']),
    ('Networks', ['NeuralNetwork', 'Neuron', 'Connection']),
    ('HyperNEAT', ['Substrate']),
    ('Novelty search', ['PhenotypeBehavior']),
]
ENUMS = ['ActivationFunction', 'NeuronType', 'SearchMode', 'GenomeSeedType']
LISTS = ['DoublesList', 'DoublesList2D', 'FloatsList', 'FloatsList2D', 'IntsList', 'IntsList2D',
         'GenomeList', 'SpeciesList', 'NeuronList', 'ConnectionList', 'NeuronGeneList', 'LinkGeneList',
         'PhenotypeBehaviorList']
FUNCTIONS = ['GetGenomeList', 'ZipFitness', 'EvaluateGenomeList_Serial', 'EvaluateGenomeList_Parallel',
             'Draw', 'DrawPhenotype', 'plot_nn', 'render_nn', 'Genome2NX']

INTRO = """# Python API reference

`import MultiNEAT as NEAT` gives access to everything below. The guides explain how the pieces fit
together - start with the [tutorial](tutorial.md).

Lists returned by the library (`pop.Species`, `species.Individuals`, `genome.LinkGenes`,
`net.neurons`, ...) are *references* into the C++ objects: changing an element changes the object. They
support `len()`, indexing, iteration, `append()` etc. like Python lists, and Python lists and tuples are
accepted wherever such a list is expected.

*(This page is generated by `docs/tools/gen_api.py`.)*
"""


def clean(sig):
    sig = sig.replace('MultiNEAT._MultiNEAT._physics2d.', '').replace('MultiNEAT._MultiNEAT.', '')
    sig = re.sub(r'self: \w+(, )?', '', sig)
    sig = sig.replace('typing.SupportsFloat', 'float').replace('typing.SupportsInt', 'int')
    sig = sig.replace('typing.', '').replace('collections.abc.', '')
    return sig


def describe(name, obj):
    """Returns (signatures, description) for a pybind11 or Python callable."""
    doc = inspect.getdoc(obj) or ''
    lines = doc.splitlines()
    sigs, text = [], []
    overloaded = 'Overloaded function.' in doc
    for line in lines:
        m = re.match(r'^(?:\d+\. )?' + re.escape(name) + r'\((.*)\)( -> .*)?$', line)
        if m and '*args, **kwargs' not in line:
            sigs.append(clean('%s(%s)%s' % (name, m.group(1), m.group(2) or '')))
        elif line.strip() and line.strip() != 'Overloaded function.' and '*args, **kwargs' not in line:
            text.append(line.strip())
    if not sigs:
        try:
            sigs = [name + str(inspect.signature(obj))]
        except (TypeError, ValueError):
            sigs = [name + '(...)']
    # drop the repeated docstrings of overloads
    seen = []
    for t in text:
        if t not in seen:
            seen.append(t)
    return sigs, ' '.join(seen), overloaded


def class_section(cls, name):
    out = ['\n### %s\n' % name]
    doc = inspect.getdoc(cls)
    if doc and not doc.startswith(name + '('):
        out.append(doc.splitlines()[0] + '\n')
    init = cls.__dict__.get('__init__')
    sigs = []
    if init is not None:
        sigs, text, _ = describe('__init__', init)
        sigs = [x for x in sigs if '*args' not in x]
    if sigs:
        out.append('```python')
        for s in sigs:
            out.append(s.replace('__init__(', name + '(').replace(' -> None', ''))
        out.append('```')
        if text:
            out.append(text)
    methods, props = [], []
    for attr, value in sorted(cls.__dict__.items()):
        if attr.startswith('_'):
            continue
        if isinstance(value, property):
            props.append((attr, value))
        elif callable(value) or isinstance(value, staticmethod):
            methods.append((attr, value))
    if methods:
        out.append('\n| Method | |\n|---|---|')
        for attr, value in methods:
            fn = getattr(cls, attr)
            sigs, text, _ = describe(attr, fn)
            out.append('| `%s` | %s |' % ('`<br>`'.join(sigs), text.replace('|', '\\|')))
    if props:
        out.append('\n**Attributes:** ' + ', '.join('`%s`' % a for a, _ in props))
    return out


def main():
    out = [INTRO]
    for group, names in CLASSES:
        out.append('\n## %s' % group)
        for n in names:
            out += class_section(getattr(NEAT, n), n)

    out.append('\n## Enumerations\n')
    for n in ENUMS:
        e = getattr(NEAT, n)
        out.append('* `%s`: %s' % (n, ', '.join('`%s`' % k for k in e.__members__)))
    out.append('\nThe values are compatible with integers, e.g. `int(NEAT.ActivationFunction.TANH)`.')

    out.append('\n## Functions\n\n| Function | |\n|---|---|')
    for n in FUNCTIONS:
        if not hasattr(NEAT, n):
            continue
        fn = getattr(NEAT, n)
        sigs, text, _ = describe(n, fn)
        out.append('| `%s` | %s |' % ('`<br>`'.join(sigs), text.replace('|', '\\|')))

    out.append('\n## List types\n')
    out.append(', '.join('`%s`' % n for n in LISTS) + ' - the reference list types described at the top.')

    out.append('\n## MultiNEAT.physics2d\n\nSee [the physics engine](physics2d.md) for a guide.')
    for n in ['Space', 'Body', 'Shape', 'Vec2d']:
        out += class_section(getattr(physics2d, n), n)
    out.append('\n| Function | |\n|---|---|')
    for n in ['Circle', 'Segment', 'draw_pygame']:
        sigs, text, _ = describe(n, getattr(physics2d, n))
        out.append('| `%s` | %s |' % ('`<br>`'.join(sigs), text.replace('|', '\\|')))

    open(OUT, 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
